"""M3.3: the report of the source acquisition plan, generated from its rows (never edited by hand)."""
import collections

import migration_lib as L

FAM_LABEL = {
    'EXISTING_ACCEPTED_DOCUMENT': 'A · accepted document, not linked to the vintage',
    'EXISTING_FETCHED_DOCUMENT': 'A · fetched estate document, never reviewed',
    'EXISTING_OFFICIAL_SOURCE': 'A · official source held',
    'DISCOVERED_NOT_ACQUIRED': 'B · first-party URL seen, never fetched',
    'DISCOVERED_OFFSITE_REDIRECT': 'B · first-party link redirecting off-site',
    'DISCOVERED_DEAD_LINK': 'B · URL seen, answered an error',
    'FIRST_PARTY_TARGETED': 'C · first-party page suspected',
    'OFFICIAL_SOURCE_SUSPECTED': 'C · official document suspected',
    'SOURCE_DISCOVERY_REQUIRED': 'D · source must first be found',
    'BLOCKED_BY_POLICY': 'E · blocked by robots / AI refusal / login',
}


def _f(n):
    return '{:,}'.format(n)


def _who(c):
    return ', '.join(c['estate_names'][:3]) + (' +%d' % (len(c['estate_names']) - 3) if len(c['estate_names']) > 3 else '')


def _line(c):
    conf = ' '.join('%s %d' % (k[0], v) for k, v in sorted(c['items_by_confidence'].items()))
    return '| %d | %s | %s | %s | %d | %d | %s | %s / %s | %s |' % (
        c['rank'], FAM_LABEL[c['source_family']], _who(c) or '—', c.get('domain') or '—', c['potential_gap_count'],
        c['potential_item_count'], conf, c['acquisition_effort'], c['extraction_effort'], c['yield_score'])


HEAD = ('| # | Source | Estate(s) | Domain | Gaps | Items | Confidence (H/M/L items) | Acquire / extract | Score |\n'
        '|---:|---|---|---|---:|---:|---|---|---:|')


def clusters(rows):
    """One platform: a domain serving one or several estates, or one estate's held documents."""
    out = collections.defaultdict(list)
    for c in rows:
        if c['status'] != 'RANKED':
            continue
        key = c.get('domain') or ('estate: ' + ', '.join(c['estate_names']))
        out[key].append(c)
    res = []
    for key, cs in out.items():
        effort = max((c['acquisition_effort'] if c['acquisition_effort'] != 'NONE' else c['extraction_effort'] for c in cs),
                     key=['XS', 'S', 'M', 'L', 'XL', 'UNKNOWN'].index)
        res.append({'key': key, 'gaps': len({g for c in cs for g in c['gap_ids']}),
                    'items': sum(c['potential_item_count'] for c in cs),
                    'estates': len({e for c in cs for e in c['estates']}), 'wines': len({w for c in cs for w in c['wines']}),
                    'effort': effort, 'strongest': max(cs, key=lambda c: c['yield_score']),
                    'score': round(sum(c['yield_score'] for c in cs), 3),
                    'categories': ''.join(sorted({c['category'] for c in cs}))})
    return sorted(res, key=lambda r: (-r['score'], -r['items'], r['key']))


def rating_only(best):
    """How many document-less vintages the model holds only through data/ratings.js."""
    import data_gap_analysis as A
    files = collections.defaultdict(set)
    for o in A.table('observation/observations.jsonl'):
        files[o['subject']].add(o['extraction'].get('file'))
    return sum(1 for (_, w, y) in best if files.get('vt:%s:%d' % (w, y)) == {'data/ratings.js'})


def report(rows, gaps, best):
    w = []
    a = w.append
    ranked = [c for c in rows if c['status'] == 'RANKED']
    A_ = [c for c in ranked if c['category'] == 'A']
    B_ = [c for c in ranked if c['category'] == 'B']
    items_total = sum(g['affected_count'] for g in gaps)
    vintage_items = len(best)
    bc = collections.Counter(best.values())
    a('# Phase M3.3: highest-yield source acquisition plan (audit only)\n')
    a('*Generated by `tools/m33-source-plan.py --report` from `data/audit/m3.3-source-acquisition-plan.jsonl`; '
      'do not edit by hand. Nothing was fetched, crawled, OCR\'d or written to the model; the score ranks '
      'sources, it establishes no fact.*\n')
    a('## If there is one short session for new-data acquisition\n')
    # one short session: the batch with the most weighted items whose acquisition fits in M (1-4 hours)
    # acquisition earns only what mapping cannot reach: rank by the vintages with no held document
    weight = lambda c: c['items_by_confidence'].get('HIGH', 0) * 3 + c['items_by_confidence'].get('MEDIUM', 0) * 2
    top_b = sorted([c for c in B_ if c.get('items_where_best_source', 0)],
                   key=lambda c: (-c['items_where_best_source'], -weight(c), c['rank']))
    session = [c for c in top_b if c['acquisition_effort'] in ('XS', 'S', 'M')]
    if session:
        t = session[0]
        a('**Acquire first: %s** (%s): %d document-less vintage(s) of %s, none of them reachable from a held '
          'document, through %d already-discovered first-party URL(s) naming those vintages; effort %s. At most '
          '**%d items** could resolve (confidence: %s) - only after the fetch and an evidence review of each '
          'document.\n' % (
              t.get('domain'), FAM_LABEL[t['source_family']], t['items_where_best_source'], _who(t), t['locator_count'],
              t['acquisition_effort'], t['items_where_best_source'],
              ', '.join('%d %s' % (v, k.lower()) for k, v in sorted(t['items_by_confidence'].items()))))
    a('But the larger yield needs no acquisition at all: **%s document-less vintages already have a document the '
      'evidence store accepted for exactly that wine and vintage**, unlinked in the model, and %s more have a fetched '
      'estate document headed with the year. Mapping those (category A) comes before any fetch.\n' % (
          _f(bc['EXISTING_ACCEPTED_DOCUMENT']), _f(bc['EXISTING_FETCHED_DOCUMENT'])))
    a('## 1. Baseline\n')
    a('| | |\n|---|---|')
    a('| Unresolved new-data gaps (register, verified now) | **%d** (none touched by M3.2) |' % len(gaps))
    a('| Items they hold | %s |' % _f(items_total))
    fam = collections.Counter(g['gap_key'].split('|')[0] for g in gaps)
    a('| By kind | %s |' % ', '.join('%s %d' % kv for kv in sorted(fam.items())))
    rated = rating_only(best)
    a('| Document-less vintages (items of VINTAGE_NO_DOCUMENT) | %s, of which %s are in the model only through a critic rating |' % (
        _f(vintage_items), _f(rated)))
    a('| Source candidates | %d (%d ranked, %d blocked or deferred) |\n' % (len(rows), len(ranked), len(rows) - len(ranked)))
    a('**Best evidence per document-less vintage** (each counted once, by its best source):\n')
    a('| Best source | Vintages | Category |\n|---|---:|---|')
    for k, v in bc.most_common():
        a('| %s | %s | %s |' % (FAM_LABEL.get(k, k), _f(v), FAM_LABEL.get(k, k)[0]))
    a('')
    a('## 2. Methodology\n')
    a('- **Items.** A register gap is an estate\'s whole set of document-less vintages, or one figure group; the items '
      'are what resolve one by one, so candidates are scored on items and also report the gap ids they touch.\n'
      '- **Existing corpus first.** For every item the evidence is sought in this order: an accepted evidence decision '
      'for exactly that wine and vintage not linked in the model (A); a fetched document of the estate headed with the '
      'year (A); a first-party URL the crawl saw and never fetched (B); a first-party link that redirected off-site '
      '(B); blocked (E) or dead (B, unavailable) URLs, recorded, never ranked; nothing known (D).\n'
      '- **Confidence.** A, accepted: HIGH. A, fetched: MEDIUM when the wine\'s name is in the title or address, else LOW '
      '(it may be another wine of the estate). B: HIGH when the address names the year, the wine and is a sheet (PDF or '
      'sheet word); MEDIUM with the year and one of those; LOW with the year alone.\n'
      '- **Score** (deterministic, documented in `score()`): 3 per HIGH item, 2 per MEDIUM, 1 per LOW; +3 first-party, '
      '+3 already discovered, +4 already stored, +3 three or more vintages, +2 two or more wines, +2 provenance tied to '
      'the exact document; -2 OCR, -3 broad crawling, -4 third-party only; divided by the effort midpoint (XS 0.25, S '
      '0.75, M 2.5, L 10, XL 20, UNKNOWN 20). Effort is the acquisition effort, or for held documents the mapping '
      'effort. Blocked, dead, decision-blocked and discovery-only candidates score 0 and are listed apart.\n'
      '- **Effort.** Fetch: XS up to 5 URLs, S 25, M 120, L 500, XL more (one polite request per URL, robots delay '
      '1.5 s, then an evidence review per document). Mapping held documents: XS up to 10 items, S 60, M 300, L more.\n'
      '- **Order:** score, then high-confidence gaps, then effort, then id.\n')
    a('## 3. Top 10 source candidates\n')
    a(HEAD)
    for c in ranked[:10]:
        a(_line(c))
    a('')
    a('## 4. Top source clusters\n')
    a('A cluster is one platform: an estate\'s held documents, or one domain serving one or several estates.\n')
    a('| Cluster | Categories | Gaps | Items | Estates | Wines | Effort | Strongest source | Score |\n'
      '|---|---|---:|---:|---:|---:|---|---|---:|')
    for cl in clusters(rows)[:12]:
        s = cl['strongest']
        a('| %s | %s | %d | %d | %d | %d | %s | #%d %s | %s |' % (cl['key'], cl['categories'], cl['gaps'], cl['items'],
                                                              cl['estates'], cl['wines'], cl['effort'], s['rank'],
                                                              FAM_LABEL[s['source_family']][:1], cl['score']))
    a('')
    a('## 5. Highest-yield existing-data opportunities (A: no acquisition)\n')
    a('%d candidates, %s items. The 182-strong accepted group is a mapping gap, not a source gap: the evidence store '
      'accepted the documents (Latour\'s own vintage pages, for instance), but their legacy attribution names the estate '
      'only, so the derived vintage index does not see them. M3.1 counted these vintages as needing new data; they '
      'need mapping.\n' % (len(A_), _f(sum(c['potential_item_count'] for c in A_))))
    a(HEAD)
    for c in A_[:15]:
        a(_line(c))
    a('')
    a('## 6. Highest-yield first-party acquisition opportunities (B)\n')
    a('%d first-party domains, %s items, %s URLs, all seen by the crawl on the estate\'s own site and skipped for '
      'budget, queue or size. Nothing needs crawling: each URL is known. Of those items, %s have no better source; '
      'the others are already covered by a held document (A), which mapping reaches without a fetch.\n' % (
          len(B_), _f(sum(c['potential_item_count'] for c in B_)), _f(sum(c['locator_count'] for c in B_)),
          _f(sum(c.get('items_where_best_source', 0) for c in B_))))
    a(HEAD)
    for c in B_:
        a(_line(c))
    a('')
    a('## 7. Blocked opportunities\n')
    blocked = [c for c in rows if c['status'] in ('BLOCKED_BY_POLICY', 'UNAVAILABLE_AT_KNOWN_URL',
                                                  'BLOCKED_BY_EDITORIAL_OR_IDENTITY_DECISION')]
    a('| Source | Estate(s) | Domain | Items | Why |\n|---|---|---|---:|---|')
    for c in blocked:
        a('| %s | %s | %s | %d | %s |' % (c['status'], _who(c), c.get('domain') or '—', c['potential_item_count'], c['why']))
    dec = [c for c in rows if c['open_decisions']]
    a('\nNo candidate is tied to an open identity or editorial decision (D1, D2, D5, La Parde, Terrasses, Batailley / '
      'Lynch-Moussas)%s. The documents on the Echo name before 2008 or on La Parde before 2018 would bear on D2 and '
      'the La Parde identity; none is among the document-less items.\n' % (
          '' if not dec else ' except %d, marked BLOCKED_BY_EDITORIAL_OR_IDENTITY_DECISION' % len(dec)))
    a('## 8. Low-yield opportunities, deliberately deferred\n')
    d = [c for c in rows if c['status'] in ('DEFERRED_DISCOVERY_REQUIRED', 'DEFERRED')]
    by_site = collections.Counter()
    items_site = collections.Counter()
    for c in d:
        k = c['source_key'].split('|')[-1] if c['source_family'] == 'SOURCE_DISCOVERY_REQUIRED' and c['source_key'].startswith('estate:') else c['source_family']
        by_site[k] += 1
        items_site[k] += c['potential_item_count']
    a('| Reason | Candidates | Items | Why deferred |\n|---|---:|---:|---|')
    why = {'REACHED': 'the site was crawled to an empty frontier and holds no document for these vintages: a negociant, '
                      'the WordPress media API or a sitemap may, but that is discovery, not a known source',
           'NOT_IN_UNIVERSE': 'the estate is outside the Phase 3.0 universe: no site was ever targeted',
           'UNREACHABLE': 'the site did not answer the crawl', 'BLOCKED_BY_POLICY': 'the site\'s robots.txt refuses us',
           'PARTIAL': 'the crawl stopped on budget, and nothing it saw names these vintages',
           'NO_KNOWN_SITE': 'no official site is known', 'SOURCE_DISCOVERY_REQUIRED': 'nothing known holds it',
           'FIRST_PARTY_TARGETED': 'a first-party statement is likely (an estate history or vintage page) but no such page is known',
           'OFFICIAL_SOURCE_SUSPECTED': 'the official body publishes it; the document is not known'}
    for k, n in sorted(by_site.items(), key=lambda kv: -items_site[kv[0]]):
        a('| %s | %d | %s | %s |' % (k, n, _f(items_site[k]), why.get(k, '')))
    a('')
    a('## 9. Recommended next acquisition batch\n')
    batch = [c for c in top_b if c['items_where_best_source'] >= 2 and c['acquisition_effort'] in ('XS', 'S', 'M')][:6]
    a('**First, without acquiring anything:** map the %s accepted documents to their vintages (category A, the '
      'top-ranked candidates). That is a model mapping from reviewed evidence, not a new source.\n' % _f(bc['EXISTING_ACCEPTED_DOCUMENT']))
    a('**Then one targeted acquisition batch:** the first-party URLs below, each already seen on the estate\'s own '
      'site; no crawling, one request per URL at the site\'s robots delay, each document then reviewed before any '
      'figure is taken:\n')
    a('| Domain | Estate | Vintages (H/M/L) | of which no held document | URLs | Effort |\n|---|---|---|---:|---:|---|')
    for c in batch:
        a('| %s | %s | %s | %d | %d | %s |' % (c.get('domain'), _who(c), ' '.join('%s %d' % (k[0], v) for k, v in sorted(c['items_by_confidence'].items())),
                                              c.get('items_where_best_source', 0), c['locator_count'], c['acquisition_effort']))
    a('\nTogether: %d vintages over %d URLs, %d of them with no held document at all (the rest are reached first by '
      'mapping). At most that many items could resolve; how many do depends on what the documents state.\n' % (
          sum(c['potential_item_count'] for c in batch), sum(c['locator_count'] for c in batch),
          sum(c.get('items_where_best_source', 0) for c in batch)))
    a('## 10. Unresolved limitations\n')
    a('- **Most document-less vintages have no known source.** %s of %s have nothing known to hold them, and %s of the %s '
      'are in the model only through a critic rating, with no sheet: the estates may never have published one online. '
      'Finding one is discovery (D), not acquisition.\n'
      % (_f(bc['SOURCE_DISCOVERY_REQUIRED']), _f(vintage_items), _f(rated), _f(vintage_items)) +
      '- **The URL match is lexical.** A year and a wine name in an address suggest the document; only fetching and '
      'reading it establishes what it holds.\n'
      '- **Fetched-document matches (A, MEDIUM/LOW) may concern another wine** of the estate (a second wine\'s sheet '
      'headed with the same year); each needs review.\n'
      '- **The crawl state is a snapshot** (2026-10-25): a skipped URL may have moved or gone since.\n'
      '- **Policy stands.** URLs refused by robots.txt or an AI-agent rule are never acquired, even when they name the '
      'exact document.\n')
    a('## Gate\n')
    a('**SAFE — M3.3 HIGHEST-YIELD SOURCE ACQUISITION AUDIT COMPLETE — READY FOR TARGETED ACQUISITION**\n')
    return '\n'.join(w) + '\n'
