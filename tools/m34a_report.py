"""M3.4A: the report of the mapping audit, generated from its rows (never edited by hand)."""
import collections
import re

ORDER = ['SAFE_TO_MAP', 'ESTATE_VINTAGE_ONLY', 'WINE_AMBIGUOUS', 'COLOUR_AMBIGUOUS', 'MULTI_WINE_AMBIGUOUS',
         'VINTAGE_AMBIGUOUS', 'IDENTITY_BLOCKED', 'CONFLICT', 'EVIDENCE_INSUFFICIENT', 'ALREADY_MAPPED', 'NOT_FOUND']
MEANING = {
    'SAFE_TO_MAP': 'the document itself names this wine and states this vintage; no other wine, vintage or colour competes',
    'ESTATE_VINTAGE_ONLY': 'the document names the estate and the year, never the wine: not promoted to the grand vin',
    'WINE_AMBIGUOUS': 'the document speaks of another wine of the estate, or does not name this one',
    'COLOUR_AMBIGUOUS': 'the document\'s colour contradicts the wine\'s, or it describes the red and white alike',
    'MULTI_WINE_AMBIGUOUS': 'the document also names another wine of the estate',
    'VINTAGE_AMBIGUOUS': 'the document\'s own vintage is not one year: several in its opening or headings, or a date',
    'IDENTITY_BLOCKED': 'the wine\'s identity waits on an open decision',
    'CONFLICT': 'the accepted decisions on the document name more than one estate or wine',
    'EVIDENCE_INSUFFICIENT': 'the document holds no readable text, or no evidence link carries the decision',
    'ALREADY_MAPPED': 'the model already links the document to the vintage',
    'NOT_FOUND': 'the document\'s bytes are not held',
}
EXTRACT = {'alc': 'alcohol', 'blend': 'blend', 'ph': 'pH', 'yld': 'yield', 'oak': 'new oak', 'months': 'months in barrel'}


def _f(n):
    return '{:,}'.format(n)


def _pattern(reason):
    """A reason with its particulars (years, counts, names) taken out, so like refusals group together."""
    r = re.sub(r'"[^"]*"|\([^)]*\)', '…', reason or '')
    r = re.sub(r'\b\d{4}\b', 'YYYY', r)
    r = re.sub(r'\b\d+\b', 'N', r)
    r = re.sub(r'^the document also names .*$', 'the document also names <another wine of the estate>', r)
    r = re.sub(r'^the opening names .*? on its own', 'the opening names <another wine> on its own', r)
    r = re.sub(r', not Château .*$', ', not the wine audited', r)
    r = re.sub(r': [a-z0-9-]+ / .*$', ': …', r)
    return r


def _doc(r):
    return (r['files'] or [r['artifact']])[-1] if r['files'] else r['artifact']


def gate(rows):
    """The gate's own conditions, recomputed: every candidate decided once, with a reason; SAFE rows referenced."""
    keys = [(r['estate'], r['wine'], r['vintage'], r['artifact']) for r in rows]
    problems = []
    if len(keys) != len(set(keys)):
        problems.append('a candidate appears twice')
    if any(r['disposition'] not in ORDER for r in rows):
        problems.append('a disposition outside the eleven')
    if any(not r['reason'] for r in rows):
        problems.append('a row without a reason')
    if any(r['disposition'] == 'SAFE_TO_MAP' and not (r['evidence_refs'] and r.get('proposal') and r['basis'])
           for r in rows):
        problems.append('a SAFE row without evidence references or basis')
    if any(r['disposition'] == 'SAFE_TO_MAP' and r['wine'] in {b[2] for b in CTX.get('blocked', [])} for r in rows):
        problems.append('a SAFE row on a wine an open decision governs')
    return problems


CTX = {}


def report(rows, ctx):
    CTX.clear()
    CTX.update(ctx)
    by = collections.defaultdict(list)
    for r in rows:
        by[r['disposition']].append(r)
    vint = lambda rs: len({(r['wine'], r['vintage']) for r in rs})
    safe = by['SAFE_TO_MAP']
    safe_v = {(r['wine'], r['vintage']) for r in safe}
    all_v = {(r['wine'], r['vintage']) for r in rows}
    problems = gate(rows)
    out = []
    w = out.append

    w('# Phase M3.4A — accepted evidence mapping recovery audit\n')
    w('Generated by `python tools/m34a-mapping-audit.py --report` from '
      '`data/audit/m3.4a-mapping-proposals.jsonl`; never edited by hand. **Audit and dry run only:** nothing in the '
      'model, the evidence store or the app was changed; nothing was fetched, crawled or OCR\'d; no figure was '
      'extracted. Every proposal below waits for mapping review.\n')

    w('## 1. Baseline\n')
    w('- Measured on the model as committed at M3.3 (`357f44c`): %s vintages hold no document, at %s estates.'
      % (_f(ctx['documentless']), _f(ctx['documentless_estates'])))
    w('- M3.3 found that for some of them the evidence store has ACCEPTED a held document for exactly that wine and '
      'vintage, yet the vintage-documents index does not link it: the legacy attribution named the estate only.')
    w('- An accepted decision is not taken as proof of the wine. Its target wine came from the legacy manifest, and '
      '`is_second=False` only says no second-wine name was found. The document itself must establish the mapping.')
    w('- Rules, applied in order; the first that fails decides:')
    w('  1. the wine is not governed by an open identity decision;')
    w('  2. the document is not already linked, and its bytes are held;')
    w('  3. the accepted decisions on the document name one estate, one wine and one vintage;')
    w('  4. the document has readable text (stored text, or the held PDF read as `tools/sheetreader.py` reads it);')
    w('  5. its opening (first %d characters) states the vintage, not several, and not only as a calendar date; '
      'its body does not head three or more other vintages;' % ctx['thresholds']['opening'])
    w('  6. it names no other wine of the estate, and does not speak of "the other wine" or a named cuvée;')
    w('  7. it names the wine: by its distinctive name, or by its full name within %d characters of the year, or '
      'says "grand vin" in its opening (not "grand vin de Bordeaux", not "grand vin sec");' % ctx['thresholds']['near'])
    w('  8. its stated blend is of the wine\'s colour, and it does not describe the estate\'s red and white alike;')
    w('  9. a v5 evidence link ties the accepted decision to the model ids.')
    w('- Never used as evidence of identity: the filename, the URL path, the PDF metadata, the estate alone.\n')

    w('## 2. Candidates\n')
    w('| | Count |\n|---|---:|')
    w('| Candidates (estate, wine, vintage, document) | %s |' % _f(len(rows)))
    w('| Model vintages they concern | %s |' % _f(len(all_v)))
    w('| Distinct documents | %s |' % _f(len({r['artifact'] for r in rows})))
    w('| Estates | %s |' % _f(len({r['estate'] for r in rows})))
    w('| Vintages with at least one SAFE document | %s |' % _f(len(safe_v)))
    w('')

    w('## 3. Dispositions\n')
    w('| Disposition | Candidates | Vintages | Meaning |\n|---|---:|---:|---|')
    for d in ORDER:
        w('| %s | %d | %d | %s |' % (d, len(by[d]), vint(by[d]), MEANING[d]))
    w('| **Total** | **%d** | **%d** | |' % (len(rows), len(all_v)))
    w('\nA vintage can hold several candidate documents with different dispositions; the vintage column counts '
      'each vintage once per disposition.\n')

    w('## 4. Proposed safe mappings\n')
    w('%d documents for %d vintages of %d wines at %d estates. Each would become a `LINK_ARTIFACT_TO_VINTAGE` '
      'proposal; none is applied. Role `GRAND_VIN` means the document names the grand vin by its estate name beside '
      'the year, or says "grand vin"; `NAMED_WINE` means it names a wine by its distinctive name.\n'
      % (len(safe), len(safe_v), len({r['wine'] for r in safe}), len({r['estate'] for r in safe})))
    w('| Estate | Wine | Vintage | Document | Role | Basis |\n|---|---|---:|---|---|---|')
    for r in safe:
        p = r['proposal']
        w('| %s | %s | %d | `%s` | %s | %s |' % (r['estate_name'], r['wine_name'], r['vintage'], _doc(r)[:60] or r['artifact'],
                                              p['role'], r['basis']))
    w('')

    w('## 5. Ambiguous and refused\n')
    w('Every refusal, grouped by its reason with the particulars taken out.\n')
    w('| Disposition | Reason | Candidates | Estates |\n|---|---|---:|---|')
    groups = collections.defaultdict(list)
    for r in rows:
        if r['disposition'] not in ('SAFE_TO_MAP', 'CONFLICT', 'IDENTITY_BLOCKED'):
            groups[(ORDER.index(r['disposition']), r['disposition'], _pattern(r['reason']))].append(r)
    for (_, d, p), rs in sorted(groups.items(), key=lambda kv: (kv[0][0], -len(kv[1]), kv[0][2])):
        est = collections.Counter(r['estate_name'] for r in rs)
        names = ', '.join('%s (%d)' % (e, n) for e, n in sorted(est.items(), key=lambda kv: (-kv[1], kv[0]))[:4])
        w('| %s | %s | %d | %s%s |' % (d, p, len(rs), names, ' +%d' % (len(est) - 4) if len(est) > 4 else ''))
    w('')

    w('## 6. Identity-blocked\n')
    w('The open identity decisions are not resolved here. The wines they govern, and how many document-less '
      'vintages each holds:\n')
    w('| Decision | Wine | Document-less vintages | Candidates here |\n|---|---|---:|---:|')
    for d, name, wid, n in ctx['blocked']:
        w('| %s | %s | %d | %d |' % (d, name, n, sum(1 for r in rows if r['wine'] == wid)))
    w('\n%d candidate(s) are IDENTITY_BLOCKED. None of the blocked wines has an accepted document for a '
      'document-less vintage: their accepted sheets were filed under the grand vin or not accepted. Where a '
      'blocked wine\'s name appears in a grand vin\'s document, the document is refused as MULTI_WINE_AMBIGUOUS '
      '(section 5), never mapped.\n' % len(by['IDENTITY_BLOCKED']))

    w('## 7. Conflicts\n')
    w('A document whose accepted decisions name more than one estate or wine. The decisions themselves disagree; '
      'no mapping is proposed from either side.\n')
    cg = collections.defaultdict(list)
    for r in by['CONFLICT']:
        cg[tuple(sorted({c[1] for c in r['accepted_claims']}))].append(r)
    w('| Wines the accepted decisions name | Candidates | Documents | Vintages |\n|---|---:|---:|---:|')
    for k, rs in sorted(cg.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        w('| %s | %d | %d | %d |' % (' · '.join(k), len(rs), len({r['artifact'] for r in rs}), vint(rs)))
    w('')

    w('## 8. Patterns\n')
    est = collections.Counter(r['estate_name'] for r in rows if r['disposition'] != 'SAFE_TO_MAP')
    w('- **Group sheets carry several estates.** %d of the %d conflicts are documents of one producer group whose '
      'sheets were accepted for two of its estates at once (the decisions name %s). The sheet names one château; '
      'the other estate\'s acceptance is the error, and is for evidence review, not for this audit.'
      % (max((len(v) for v in cg.values()), default=0), len(by['CONFLICT']),
         ' and '.join(max(cg.items(), key=lambda kv: len(kv[1]))[0]) if cg else '—'))
    w('- **Estate-and-vintage sheets.** %d candidates name the estate and the year, never the wine. Most are a '
      'producer\'s series whose title is an image, or vintage pages that describe the season, not a wine. They stay '
      'unmapped: the grand vin is not assumed.' % len(by['ESTATE_VINTAGE_ONLY']))
    w('- **Vintage compilations.** %d candidates are documents that carry several vintages (a press digest, a '
      'vertical, a multi-year sheet), or whose opening states a different year. The accepted decision chose one '
      'year among several.' % len(by['VINTAGE_AMBIGUOUS']))
    w('- **One model wine, several real ones.** Where the model lists one wine and the estate makes more, a sheet '
      'for the unlisted wine looks like the listed one. The colour test caught white sheets filed under a red wine '
      'and a document describing the red and white alike (%d); the sibling test caught a second wine whose name lies '
      'inside the estate\'s.' % len(by['COLOUR_AMBIGUOUS']))
    w('- **Most refusals concentrate in few estates:** %s.\n'
      % ', '.join('%s %d' % kv for kv in sorted(est.items(), key=lambda kv: (-kv[1], kv[0]))[:6]))

    w('## 9. Extraction opportunities\n')
    w('Recorded, not extracted: for each SAFE mapping, the core figures the model does not yet hold for the vintage. '
      'A later phase may read them from the mapped document.\n')
    ex = collections.Counter(f for r in safe for f in r.get('extraction_opportunity') or [])
    w('| Figure | SAFE documents that could supply it |\n|---|---:|')
    for f in sorted(EXTRACT, key=lambda f: (-ex[f], f)):
        w('| %s | %d |' % (EXTRACT[f], ex[f]))
    w('\nAcross %d vintages: %d (figure, vintage) slots open.\n'
      % (len(safe_v), len({(r['wine'], r['vintage'], f) for r in safe for f in r.get('extraction_opportunity') or []})))

    w('## 10. Recommendation\n')
    w('- Review the %d SAFE proposals (section 4) and, once approved, apply them in a separate mutation phase as '
      'links from document to vintage, with this audit\'s evidence references as provenance.' % len(safe))
    w('- Do not map the refused candidates. The conflicts (section 7) are an evidence-store question: which of '
      'the group\'s estates each sheet is for.')
    w('- The estate-and-vintage sheets need either an accepted decision that names the wine, or a reader for '
      'the image titles; neither is in scope here.')
    w('- The identity decisions in section 6 stay open; nothing here depends on them.\n')

    if problems:
        w('**Gate: BLOCKED** — %s.\n' % '; '.join(problems))
    else:
        w('**Gate: SAFE — M3.4A EXISTING EVIDENCE MAPPING AUDIT COMPLETE — READY FOR MAPPING REVIEW**\n')
    return '\n'.join(out)
