"""M3.4B: the report of the mapping application, generated from its manifest (never edited by hand)."""
import collections
import json
import subprocess

import migration_lib as L

BEFORE = '8b1c25b'               # M3.4A
FILES = ('document/attributions.jsonl', 'cross/provenance.jsonl', 'canonical/values.jsonl',
         'observation/observations.jsonl', 'observation/evidence-links.jsonl', 'identity/artifacts.jsonl',
         'identity/vintages.jsonl', 'cross/findings.jsonl', 'reconciliation/reconciliations.jsonl')


def _git(*a):
    return subprocess.check_output(['git'] + list(a), cwd=L.ROOT).decode('utf-8')


def _f(n):
    return '{:,}'.format(n)


def _documented(vd):
    return sum(1 for v in vd.values() if v)


def report(rows, allow):
    applied = [r for r in rows if r['result'] == 'APPLIED']
    rejected = [r for r in rows if r['result'] != 'APPLIED']
    m0 = json.loads(_git('show', '%s:data/model/manifest.json' % BEFORE))
    m1 = json.load(open(L.MODEL + 'manifest.json', encoding='utf-8'))
    vd0 = json.loads(_git('show', '%s:data/model/derived/vintage-documents.json' % BEFORE))
    vd1 = json.load(open(L.MODEL + 'derived/vintage-documents.json', encoding='utf-8'))
    vintages = sum(1 for _ in open(L.MODEL + 'identity/vintages.jsonl', encoding='utf-8'))
    changed = sorted(f[len('data/model/'):] for f in _git('diff', '--name-only', BEFORE, '--', 'data/model').split())
    out = []
    w = out.append

    w('# Phase M3.4B — audited existing-evidence mappings applied\n')
    w('Generated by `python tools/m34b-apply.py --report` from `data/audit/m3.4b-mapping-application.jsonl`; '
      'never edited by hand. The one intended change: accepted documents the M3.4A audit found unlinked are now '
      'linked, as evidence, to their audited estate + wine + vintage. Nothing was fetched, crawled or OCR\'d; no '
      'figure was extracted; no conflict or identity decision was made.\n')

    w('## 1. M3.4A baseline\n')
    w('- The allow-list is M3.4A\'s `SAFE_TO_MAP` rows (`data/audit/m3.4a-mapping-proposals.jsonl`, commit `%s`), '
      'and nothing else: %d mappings, %d vintages, %d wines, read from the audit and matched to its report.'
      % (BEFORE, len(allow), len({r['vintage_id'] for r in allow}), len({r['wine'] for r in allow})))
    w('- Before applying, a fresh M3.4A run reproduced every SAFE row byte for byte.')
    refused = sum(1 for r in L.jsonl_lines(L.ROOT + 'data/audit/m3.4a-mapping-proposals.jsonl')
                  if r['disposition'] != 'SAFE_TO_MAP')
    w('- No other mapping was looked for. The %d refused candidates stay refused.\n' % refused)

    w('## 2. Proposed, applied, rejected\n')
    w('| | Count |\n|---|---:|')
    w('| Proposed (M3.4A SAFE_TO_MAP) | %d |' % len(allow))
    w('| Applied | %d |' % len(applied))
    w('| Rejected in preflight | %d |' % len(rejected))
    w('| Vintages newly linked | %d |' % len({r['vintage_id'] for r in applied}))
    w('| Wines represented | %d |' % len({r['wine'] for r in applied}))
    w('| Estates represented | %d |' % len({r['estate'] for r in applied}))
    w('')
    w('The fail-closed preflight (`tools/m34b-apply.py`) checks, for each row, against the model as it stood '
      'before M3.4B:\n')
    w('- **Artifact:** it exists with the same id and sha256, its held file re-hashes to it, and its manifest provenance is present.')
    w('- **Evidence:** at least one referenced v5 decision is ACCEPTED, read exactly these bytes, and names this estate, wine, '
      'vintage and the grand-vin role. Its evidence link carries the model ids.')
    w('- **Estate and wine:** both exist, and the wine is the estate\'s in the model. No open decision governs the wine, '
      'and the document names no wine one governs.')
    w('- **Vintage:** it exists, had no document, is the decision\'s, and stands in the document\'s own opening.')
    w('- **Role and colour:** they are as M3.4A recorded them, and the wine\'s colour is unchanged in the model.')
    w('- **Conflicts:** no other attribution of the artifact names another wine or vintage, and no two proposals '
      'for one artifact disagree.\n')
    if rejected:
        w('| Rejected | Failures |\n|---|---|')
        for r in rejected:
            w('| %s %d `%s` | %s |' % (r['wine_name'], r['vintage'], r['artifact'], '; '.join(r['failures'])))
        w('')

    w('## 3. Mappings\n')
    w('Several documents for one vintage are each kept: language versions and copies are distinct accepted '
      'artifacts, not deduplicated.\n')
    w('| Estate | Wine | Vintage | Artifact | Document | Attribution | Accepted decision(s) |\n'
      '|---|---|---:|---|---|---|---:|')
    for r in rows:
        w('| %s | %s | %d | `%s` | `%s` | `%s` | %d |' % (r['estate_name'], r['wine_name'], r['vintage'], r['artifact'],
                                                       (r['files'][-1] if r['files'] else '')[:56], r['attribution'],
                                                       len(r['evidence_decisions'])))
    w('')

    w('## 4. Evidence and provenance preservation\n')
    w('- **What a mapping is.** Each mapping is one new Attribution (method `DOCUMENT_TEXT`, status `ACCEPTED`, '
      'role `FIRST`) beside the artifact\'s manifest attribution. The manifest attribution named the estate only, '
      'and is not changed.')
    w('- **Its provenance.** Each Attribution has its own DOCUMENT provenance (actor `tools/m34b-apply.py`, stream '
      '`M3.4B`). It quotes the audit\'s basis, records the sha256 and the accepted decision id(s) (the evidence-link '
      'row key), and derives from the artifact\'s original `LEGACY_MANIFEST` provenance.')
    w('- **Nothing rewritten.** No evidence decision, artifact, content hash, placement, URL or earlier attribution '
      'was changed or removed.')
    other = [(r, o) for r in rows for o in r['other_decisions']]
    if other:
        w('- **Decisions kept beside the mapping.** M3.4A listed every v5 link on the document, so %d of its '
          'references are not acceptances for this target:' % len(other))
        for r, o in other:
            w('  - %s %d `%s`: %s %s for %s, which agrees with the mapping. The guard kept the %d sheet off %s.'
              % (r['wine_name'], r['vintage'], r['artifact'], o['result'], o['code'], o['vintage'], r['vintage'], o['vintage']))
        w('  - The manifest keeps them as `other_decisions`. The mapping rests only on the accepted ones.')
    notes = sorted({n for r in rows for n in r['notes']})
    for n in notes:
        w('- Noted in preflight: %s.' % n)
    w('- **What a mapping does not mean:** that the document\'s figures are accepted, that it is the source of '
      'any field, or anything about other vintages, the wine\'s history or its identity.\n')

    w('## 5. Before and after\n')
    w('| Table | Rows before | Rows after |\n|---|---:|---:|')
    for f in FILES:
        a, b = m0['files'][f]['rows'], m1['files'][f]['rows']
        w('| %s | %s | %s%s |' % (f, _f(a), _f(b), '' if a == b else ' (+%d)' % (b - a)))
    w('| vintages with a document | %s of %s | %s of %s |' % (_f(_documented(vd0)), _f(vintages), _f(_documented(vd1)), _f(vintages)))
    w('| vintage–document links | %s | %s |' % (_f(sum(len(v) for v in vd0.values())), _f(sum(len(v) for v in vd1.values()))))
    w('\nModel files changed since M3.4A: %s. App data (`data/app/`): unchanged. The legacy projection reads '
      'manifest attributions only.\n' % ', '.join('`%s`' % c for c in changed))

    w('## 6. Unintended-change audit\n')
    w('- **Model diff.** Exactly the four files above changed, by additions only: %d attributions, %d provenance '
      'rows, %d vintages gaining their first documents, and one manifest stat (`M6 M3.4B audited mappings`).'
      % (len(applied), len(applied), len({r['vintage_id'] for r in applied})))
    w('- **Untouched.** Unchanged since `%s`: values, observations, reconciliations, findings, transitions, artifacts, '
      'evidence links, the evidence store, and the app and legacy files.' % BEFORE)
    w('- **Audits.** The M3.3 plan, the M3.4A audit and the gap register still reproduce byte for byte. Each '
      'measures the model as it stood before M3.4B (`data_gap_analysis.vintage_documents`); the register then '
      'records what M3.4B resolved.')
    w('- **Open decisions.** D1, D2, D5, La Parde/Haut-Bailly II, Terrasses, Batailley/Lions and Lynch-Moussas/Hauts '
      'are unchanged: 179 D1 findings and 7 conflicts stay open, with no transition.\n')

    w('## 7. Tests\n')
    w('`tools/test-m34b.py` checks the following.\n')
    w('- **Coverage:** every allow-list entry is applied, none is missing, and no extra mapping exists.')
    w('- **Targets:** each mapping points to its artifact, whose hash is unchanged.')
    w('- **Preservation:** evidence decision ids and provenance are preserved.')
    w('- **Identity:** estate, wine and vintage are exact, and no open decision changed.')
    w('- **No new facts:** no figure or value was added.')
    w('- **Reproducibility:** generation is deterministic, the M3.4A output is unchanged, and the model, indexes '
      'and app data rebuild.')
    w('- **Consistency:** the generated data agrees with itself.\n')
    w('Earlier suites whose checks guard "only named phases changed the model" admit M3.4B through '
      '`tools/historical_m2_scope.py`. It names the change exactly: each added attribution must be an APPLIED row of '
      'the manifest, with its M3.4B provenance. Their assertions about every other row stand unchanged.\n')

    w('## 8. Limitations\n')
    w('- **Scope.** Only %d of the 182 vintages M3.4A examined gain a document. The others need evidence review: '
      'the Bernaleau group conflicts, the estate-only sheets, and the multi-vintage documents.' % len({r['vintage_id'] for r in applied}))
    w('- **No figures.** The linked documents\' figures are not read; M3.4A section 9 records them as extraction '
      'opportunities.')
    w('- **Role.** Every mapping is to a grand vin (role FIRST), the only role M3.4A proposed.\n')

    w('## 9. Next recommended phase\n')
    w('Held-document review: the M3.4A refusals that existing evidence could settle. Start with the Bernaleau group '
      'sheets accepted for two estates, then the estate-and-vintage sheets whose titles are images. Extraction from '
      'the newly linked documents comes after, as its own phase. Acquisition (M3.3\'s plan) waits.\n')

    if rejected or len(applied) != len(allow):
        w('**Gate: BLOCKED — M3.4B FAIL-CLOSED PREFLIGHT FOUND A MAPPING DISCREPANCY**\n')
    else:
        w('**Gate: SAFE — M3.4B AUDITED EVIDENCE MAPPINGS APPLIED — READY FOR HELD-DOCUMENT REVIEW**\n')
    return '\n'.join(out)
