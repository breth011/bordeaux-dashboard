"""M3.5: the report of the held-document review, generated from its rows (never edited by hand)."""
import collections
import json

import migration_lib as L

POPS = ['BERNALEAU_PILOT', 'WIDER_ACCEPTED', 'WIDER_FETCHED']
ORDER = ['SAFE_TO_ATTRIBUTE', 'ALREADY_SUPPORTED', 'BOTH_ESTATES_SUPPORTED', 'CONFLICT_REMAINS', 'WINE_AMBIGUOUS',
         'VINTAGE_AMBIGUOUS', 'MULTI_WINE_AMBIGUOUS', 'COLOUR_AMBIGUOUS', 'ESTATE_AMBIGUOUS', 'EVIDENCE_INSUFFICIENT',
         'WRONG_EXISTING_ATTRIBUTION', 'NOT_RELEVANT']
OUTCOMES = ['BRAUDE_ONLY', 'MONGRAVEY_ONLY', 'BOTH_ESTATES', 'NEITHER', 'AMBIGUOUS']
EXTRACT = {'alc': 'alcohol', 'blend': 'blend', 'ph': 'pH', 'yld': 'yield', 'oak': 'new oak', 'months': 'months in barrel'}


def _f(n):
    return '{:,}'.format(n)


def _doc(r):
    return ([f for f in r['files'] if f] or [r['artifact']])[-1]


def report(rows):
    by = collections.defaultdict(list)
    for r in rows:
        by[r['population']].append(r)
    pilot = by['BERNALEAU_PILOT']
    docs = {}
    for r in pilot:
        docs[r['artifact']] = r
    outcome = collections.Counter(r['pilot_outcome'] for r in docs.values())
    elig = [r for r in rows if r['eligible']]
    m34a = [r for r in L.jsonl_lines(L.ROOT + 'data/audit/m3.4a-mapping-proposals.jsonl') if r['disposition'] == 'CONFLICT'
            and {c[1] for c in r['accepted_claims']} >= {'Château de Braude', 'Château Mongravey'}]
    reg = L.jsonl_lines(L.ROOT + 'data/audit/data-gap-register.jsonl')
    out = []
    w = out.append

    w('# Phase M3.5 — held-document review and the Bernaleau conflict pilot\n')
    w('Generated by `python tools/m35-review.py --report` from `data/audit/m3.5-held-document-review.jsonl`; never '
      'edited by hand. Existing data only: nothing was fetched, crawled or OCR\'d, no figure was read into the model, '
      'no D5 policy was adopted, and no open identity decision was resolved. The question for every candidate was '
      'what exact estate, wine and vintage relationship the held document itself establishes.\n')

    w('## 1. Baseline\n')
    w('Recalculated on the model as it stands after M3.4B, not assumed:\n')
    w('| | Expected (earlier audits) | Now |\n|---|---|---|')
    w('| Bernaleau cluster, on vintages with no document | 142 conflict candidates, 57 documents (M3.4A: 134 of them '
      'Braude/Mongravey) | %d candidates, %d documents (M3.4A\'s file) |' % (len(m34a), len({r['artifact'] for r in m34a})))
    w('| Bernaleau cluster, every accepted claim | — | %d documents accepted for both estates; %d distinct claims '
      '(estate, wine, vintage) on them |' % (len(docs), len(pilot)))
    w('| Accepted held documents for a vintage with no document (other documents) | — | %d candidates, %d vintages |'
      % (len(by['WIDER_ACCEPTED']), len({r['vintage_id'] for r in by['WIDER_ACCEPTED']})))
    w('| Fetched estate documents never reviewed, for a vintage with no document | about 140 vintages (M3.3, as best '
      'source) | %d candidates, %d vintages, %d documents |' % (len(by['WIDER_FETCHED']),
                                                             len({r['vintage_id'] for r in by['WIDER_FETCHED']}),
                                                             len({r['artifact'] for r in by['WIDER_FETCHED']})))
    w('\nThe 140 of M3.3 counted only the vintages whose *best* source was a fetched document. Here, every vintage '
      'with any fetched candidate counts, so vintages that also have an accepted document are included.\n')

    w('## 2. Bernaleau pilot\n')
    w('Run first, before any other document and before any change to the model. All %d documents have a title '
      'line (rule T1), and every claim got a disposition the rubric names, so the pilot gate passed and the wider '
      'review ran.\n' % len(docs))
    w('| Document outcome | Documents | Titles |\n|---|---:|---|')
    titles = collections.defaultdict(collections.Counter)
    for r in docs.values():
        titles[r['pilot_outcome']][(r['title'] or ['?'])[0]] += 1
    for o in OUTCOMES:
        w('| %s | %d | %s |' % (o, outcome[o], ', '.join('%s (%d)' % kv for kv in sorted(titles[o].items())) or '—'))
    w('\n| Claim disposition | Claims | Eligible |\n|---|---:|---:|')
    pc = collections.Counter(r['disposition'] for r in pilot)
    for d in ORDER:
        if pc[d]:
            w('| %s | %d | %d |' % (d, pc[d], sum(1 for r in pilot if r['disposition'] == d and r['eligible'])))
    w('\nAn example of each decision type:\n')
    seen = set()
    for r in pilot:
        k = (r['pilot_outcome'], r['disposition'])
        if k in seen:
            continue
        seen.add(k)
        w('- **%s / %s:** `%s`, claimed as %s %d. %s.' % (r['pilot_outcome'], r['disposition'], _doc(r),
                                                       r['wine_name'], r['vintage'], r['basis']))
    w('\nNo pilot document supports both estates, and none is left conflicted: each is one wine\'s sheet or press '
      'dossier. "Mongravey" appears on every one of them, but only in the producer line (SARL Mongravey, '
      '@mongravey.fr), which rule T3 sets aside. The rubric is deterministic: the title line decides, and nothing '
      'in the pilot needed a judgement outside the rules below.\n')

    w('## 3. Pilot decision rubric\n')
    w('`tools/m35_rubric.py`, applied to the document\'s own text. The first rule that decides wins.\n')
    w('- **T1 — title.** The document\'s first non-empty line is its title when it is a bare name phrase: it opens '
      'with château, clos, domaine or cuvée, or is a model wine\'s whole name, followed by at most a year. A heading '
      '("Le climat") is no title.')
    w('- **T2 — exact name.** The title must equal a model wine\'s name, normalised (accents, case, hyphens, "ch.").')
    w('  - A shared word is no match: "Château Braude Fellonneau" is not "Château de Braude".')
    w('  - A title naming another model wine, or a wine the model does not list, makes the claim '
      'WRONG_EXISTING_ATTRIBUTION.')
    w('- **T3 — producer lines.** Lines naming the company, address, telephone, e-mail or site are not identity, '
      'and are never read for another wine.')
    w('- **T4 — vintage.** The title\'s year is the vintage, and a claim for another year is wrong.')
    w('  - A year in a dated line ("dec 2022", "guide hubert des vins 2017") is a date, never a vintage.')
    w('  - Filenames, URLs and metadata are never read.')
    w('  - A title without a year leaves the vintage ambiguous.')
    w('- **T5 — scope.** No other wine of the estate may be named outside the producer lines, and "l\'autre vin" or a '
      'second wine in the opening makes the wine ambiguous.')
    w('  - A document naming each claimed wine beside the one vintage is a shared sheet (both supported).')
    w('- **T6 — colour.** A stated blend must be of the wine\'s colour.')
    w('- **T7 — open decisions.** A wine an open identity decision governs is never attributed (Echo, Lions de '
      'Batailley, Hauts de Lynch-Moussas, Haut-Bailly II, Terrasses).')
    w('- **Fallback.** A document with no title is judged by M3.4A\'s rules, unchanged. Their dispositions carry over: '
      'ESTATE_VINTAGE_ONLY and IDENTITY_BLOCKED become WINE_AMBIGUOUS, CONFLICT becomes CONFLICT_REMAINS.')
    w('- **O1 — no decision, no attribution.** A document never put to the evidence store has no accepted decision, '
      'and is not attributed (Part O).')
    w('- **Eligible.** A SAFE (or shared) claim is eligible only when an ACCEPTED decision on these exact bytes names '
      'exactly that estate, wine, vintage and role, the held file re-hashes, and the artifact\'s manifest provenance exists.\n')

    w('## 4. False positives caught\n')
    wrong = [r for r in pilot if r['disposition'] == 'WRONG_EXISTING_ATTRIBUTION']
    dated = [r for r in rows if r['population'] != 'WIDER_FETCHED' and r['claim_year_dated']]
    by_title = collections.Counter((r['title'] or ['?'])[0] for r in wrong)
    w('- **Accepted for the wrong estate.** %d pilot claims were ACCEPTED in the evidence store for a wine the '
      'document is not:' % len(wrong))
    w('  - The cause: the guard checked year and second-wine, never the estate. The group\'s shared media library put '
      'every sheet in both estates\' folders.')
    w('  - Claims by title: %s.' % ', '.join('%s %d' % kv for kv in sorted(by_title.items())))
    w('  - Each is recorded as a correction proposal. No decision was changed.')
    w('- **Spurious vintages.** Mongravey\'s sheets were accepted as Braude **1981**, and Braude\'s as Mongravey '
      '**1984**: years printed in the sheets, not their vintage. T4 refuses them.')
    w('- **Dates read as vintages.** %d accepted claims name a year the document prints only in a dated line, '
      'such as a press date. Examples: %s.' % (len(dated), '; '.join('`%s` claimed as %d' % (_doc(r), r['vintage'])
                                                               for r in dated[:4]) or 'none'))
    w('- **Rules the review itself had to correct:**')
    w('  - A section heading ("Le climat", on a Laville Haut-Brion sheet) parsed as a title naming an unknown wine. T1 '
      'now requires a strong opening word, or a model wine\'s whole name.')
    w('  - The producer-line pattern first matched French prose ("sa") and bottle counts. It now requires company '
      'forms, a Gironde postcode before a town, or a full telephone number.')
    w('- **M3.4A\'s refusals still hold.** Estate-wide vintage pages, white sheets under a red wine, *Mondot*, event '
      'dates and press digests are re-judged by the same rules. None became eligible (section 7, and '
      '`tools/test-m35.py`).\n')

    w('## 5. Applied safe relationships\n')
    nv = {r['vintage_id'] for r in elig if r['gap_id']}
    w('%d attributions (%d vintages, %d of them vintages that had no document), each through the preflight, '
      'applied as Attributions (method DOCUMENT_TEXT, status ACCEPTED). Each has a DOCUMENT provenance naming the '
      'accepted decision(s) and deriving from the artifact\'s manifest provenance. The original manifest attribution, '
      'the artifact and every decision are unchanged.\n'
      % (len(elig), len({r['vintage_id'] for r in elig}), len(nv)))
    w('| Wine | Vintage | Document | Type | Rule | Had no document |\n|---|---:|---|---|---|---|')
    for r in elig:
        w('| %s | %d | `%s` | %s | %s | %s |' % (r['wine_name'], r['vintage'], _doc(r)[:48], r['document_type'],
                                                 r['rule'], 'yes' if r['gap_id'] else 'no'))
    w('')

    w('## 6. Conflicts retained\n')
    con = [r for r in rows if r['disposition'] == 'CONFLICT_REMAINS']
    w('%d candidates stay conflicted. The accepted decisions on the document name more than one estate, and the '
      'document has no title to decide by. No mapping is proposed from either side, and no recency, domain or '
      'majority rule is used.\n' % len(con))
    w('| Wine | Vintage | Document | Why |\n|---|---:|---|---|')
    for r in con:
        w('| %s | %d | `%s` | %s |' % (r['wine_name'], r['vintage'], _doc(r)[:50], r['basis'][:140]))
    w('')

    w('## 7. Wider held-document results\n')
    w('| Disposition | Wider accepted | Wider fetched |\n|---|---:|---:|')
    for d in ORDER:
        a = sum(1 for r in by['WIDER_ACCEPTED'] if r['disposition'] == d)
        f = sum(1 for r in by['WIDER_FETCHED'] if r['disposition'] == d)
        if a or f:
            w('| %s | %d | %d |' % (d, a, f))
    w('| **Total** | **%d** | **%d** |' % (len(by['WIDER_ACCEPTED']), len(by['WIDER_FETCHED'])))
    rules = collections.Counter(r['rule'] for r in by['WIDER_ACCEPTED'])
    w('\n- **Wider accepted.** %d candidates were judged by the title rule and %d by M3.4A\'s fallback. None became '
      'eligible: M3.4A already mapped every document its rules could, and the title rule finds no new one.'
      % (rules['T'], rules['M34A']))
    w('  - What the title rule does find: Cuvée de Mongravey sheets accepted as Château Mongravey (wrong existing '
      'attributions), and documents whose title carries no year.')
    w('- **Wider fetched.** All %d candidates are EVIDENCE_INSUFFICIENT: the documents were fetched but never put to '
      'the evidence store, so no accepted decision exists to attribute from (O1).'
      % len(by['WIDER_FETCHED']))
    w('  - Their first lines are recorded as information only. They are mostly web-page titles, not the document\'s '
      'own heading.')
    types = collections.Counter(r['document_type'] for r in rows)
    w('- **Document types** (a text heuristic, recorded for review, not used to decide): %s.\n'
      % ', '.join('%s %d' % kv for kv in sorted(types.items())))

    w('## 8. Extraction opportunities\n')
    ex = collections.Counter(f for r in elig for f in r.get('extraction_opportunity') or [])
    w('Recorded, not extracted: the core figures the model does not hold for each newly attributed vintage.\n')
    w('| Figure | Attributed documents that could supply it |\n|---|---:|')
    for f in sorted(EXTRACT, key=lambda f: (-ex[f], f)):
        w('| %s | %d |' % (EXTRACT[f], ex[f]))
    w('')

    w('## 9. Remaining gaps\n')
    props = [r for r in rows if r.get('correction_proposal')]
    m35 = [g for g in reg if any(b['phase'] == 'M3.5' for b in (g.get('resolution') or {}).get('by', []))]
    w('- **Correction proposals.** %d wrong existing attributions (%d accepted decisions) await separate '
      'reconciliation. They are proposals only: no decision is refused here.'
      % (len(props), len({d for r in props for d in r['correction_proposal']['decisions']})))
    w('- **Fetched documents.** %d of them (%d vintages) need an evidence-store review before any attribution: the '
      'cheapest next source of documents, with no acquisition needed.'
      % (len({r['artifact'] for r in by['WIDER_FETCHED']}), len({r['vintage_id'] for r in by['WIDER_FETCHED']})))
    w('- **The gap register** records M3.5 on %d estate gap(s) (`VINTAGE_NO_DOCUMENT`), with its commit, keeping each '
      'gap\'s id, original count and earlier history. Only "no document" is resolved; the vintages\' figures stay '
      'with their own gaps.' % len(m35))
    w('- **Unchanged.** The conflicts in section 6, the open identity decisions, and D1 and D5 stay open.\n')

    w('## 10. Recommendation for the next phase\n')
    w('- **Next phase: evidence review of the fetched estate documents** (section 9): put them to the evidence store\'s '
      'reader, then attribute by this rubric. Done before targeted acquisition, it may document vintages without '
      'fetching anything new.')
    w('- **Reconciliation of the correction proposals:** the Bernaleau sheets accepted for the wrong estate, and the '
      'Cuvée de Mongravey sheets accepted as the château. This needs the user\'s decision on how a refusal is recorded.')
    w('- **Targeted acquisition (M3.3\'s plan)** follows, for the vintages that neither held nor fetched documents can '
      'cover.\n')
    stop = [r for r in pilot if r['pilot_outcome'] == 'AMBIGUOUS' or r['rule'] != 'T']
    if stop:
        w('**Gate: BLOCKED — M3.5 BERNALEAU PILOT REQUIRES REVIEW**\n')
    else:
        w('**Gate: SAFE — M3.5 HELD-DOCUMENT REVIEW COMPLETE — READY FOR TARGETED ACQUISITION**\n')
    return '\n'.join(out)
