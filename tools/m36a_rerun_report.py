"""M3.6A rerun: the report, generated from the rerun's rows and the blocked run's frozen summary (never edited by hand)."""
import collections

ORDER = ['SAFE_TO_MAP', 'ALREADY_SUPPORTED', 'ESTATE_ONLY', 'WINE_AMBIGUOUS', 'VINTAGE_AMBIGUOUS', 'MULTI_WINE_AMBIGUOUS',
         'COLOUR_AMBIGUOUS', 'ROLE_AMBIGUOUS', 'EVIDENCE_INSUFFICIENT', 'IDENTITY_BLOCKED', 'CONFLICT', 'NOT_RELEVANT']
EXTRACT = {'alc': 'alcohol', 'blend': 'blend', 'ph': 'pH', 'yld': 'yield', 'oak': 'new oak', 'months': 'months in barrel'}


def _f(n):
    return '{:,}'.format(n)


def report(props, corr, fps, base, blocked):
    out = []
    w = out.append
    safe = [r for r in props if r['disposition'] == 'SAFE_TO_MAP']
    gate = [r for r in safe if r['r1_gate']]
    fp = [r for r in props if r['reader_false_positive']]
    unknown = [r for r in fp if not r['reader_false_positive']['known']]
    disp = collections.Counter(r['disposition'] for r in props)

    w('# Phase M3.6A, run again — fetched-document reader audit and evidence-correction audit\n')
    w('Generated by `python tools/m36a-rerun.py --report` from `data/audit/m3.6a-rerun-held-document-proposals.jsonl`, '
      '`data/audit/m3.6a-rerun-evidence-corrections.jsonl` and the blocked run\'s frozen summary '
      '(`data/audit/m3.6a-blocked-run-summary.json`); never edited by hand.\n')
    w('**Audit only.** Nothing was mapped or corrected: no evidence decision, model row, provenance, gap record or '
      'app file changed. Nothing was fetched, crawled or OCR\'d, and no figure entered the model.\n')

    w('## 1. Preconditions and fingerprints\n')
    w('The controlled web-page rule update is `0564fcb`; this run uses it as committed.\n')
    w('| | |\n|---|---|')
    w('| Reader (`sheetreader.py` + `read-fiches.py`) | `%s` (the v5 decisions were made by `%s`) |' % (
        fps['reader'], ', '.join(x or 'none' for x in fps['reader_of_v5_decisions'])))
    w('| Web-page rules (`tools/web_evidence.py`) | `%s` |' % fps['web_rules'])
    w('| M3.5 rubric (`tools/m35_rubric.py`) | `%s` |' % fps['rubric'])
    w('| M3.4A rules (`tools/m34a-mapping-audit.py`) | `%s` |' % fps['m34a_rules'])
    w('| Model contract (`tools/model_schema.py`, `%s`) | `%s` |' % (fps['model_contract_file'], fps['model_contract']))
    w('| Evidence schema | %s, decider version %d |' % (fps['evidence_schema'], fps['decider_version_v5']))
    w('\nA change to any of these invalidates this audit; the rerun must then be repeated.\n')

    w('## 2. Verified baseline\n')
    w('| | Blocked run | This run |\n|---|---:|---:|')
    w('| Fetched-document candidates (document, estate, wine, vintage) | %s | %s |' % (_f(blocked['candidates']), _f(len(props))))
    w('| Documents | %s | %s |' % (_f(blocked['documents']), _f(len({r['artifact'] for r in props}))))
    w('| Vintages | %s | %s |' % (_f(blocked['vintages']), _f(len({r['vintage_id'] for r in props}))))
    w('| SAFE_TO_MAP | %s | %s |' % (_f(blocked['dispositions'].get('SAFE_TO_MAP', 0)), _f(disp['SAFE_TO_MAP'])))
    w('| Reader acceptances (whose_sheet raised no objection) | %s | %s |' % (
        _f(blocked['reader'].get('ACCEPTED', 0)), _f(sum(1 for r in props if r['reader']['decision'] == 'ACCEPTED'))))
    w('| Wrong accepted claims audited | %s | %s |' % (_f(blocked['corrections']), _f(len(corr))))
    w('\nMeasured on the model as it stands (after M3.4B and M3.5):')
    w('- M3.3\'s fetched-document items number %s.' % _f(base['items_before_documenting']))
    w('- %s of them (%s vintages) are no longer candidates: those vintages now have a document.' % (
        _f(base['removed_documented_since']), _f(base['removed_vintages'])))
    w('- The population is the same as the blocked run\'s: the model has not changed since.')
    w('- The candidates cover %s web pages and %s PDFs.\n' % (
        _f(sum(1 for r in props if r['media_type'] == 'text/html')), _f(sum(1 for r in props if r['media_type'] == 'application/pdf'))))

    w('## 3. How each document was judged\n')
    w('- **A web page** is judged by `tools/web_evidence.py` on its stored structure:')
    w('  - Its identity is its visible main heading. The tab title, URL, filename, folder and domain are never read.')
    w('  - Only its content region counts. Navigation, sidebars, related products, recommendation, archive and list '
      'regions are excluded, and their matches are kept only as diagnostics.')
    w('  - Its page type is decided before any mapping, and its vintage must come from the heading or a labelled field.')
    w('- **A PDF** is judged by the M3.5 rubric. A PDF with no title is judged by M3.4A\'s rules, unchanged.')
    w('- **The v5 reader** (`whose_sheet`, unmodified) is a veto, never a basis. A SAFE_TO_MAP needs the document\'s own '
      'evidence and no objection from the reader. A reader acceptance the evidence rejects is recorded as a reader false '
      'positive, with its class.')
    w('- **The R1 gate.** Every SAFE_TO_MAP is checked again: a wine document, its main heading the wine\'s exact name, '
      'its vintage from the heading or a labelled field, nothing from an excluded region, no date-only year.\n')

    w('## 4. Results\n')
    w('| Disposition | Candidates | Web pages | PDFs | Vintages |\n|---|---:|---:|---:|---:|')
    for d in ORDER:
        rs = [r for r in props if r['disposition'] == d]
        if rs:
            w('| %s | %d | %d | %d | %d |' % (d, len(rs), sum(1 for r in rs if r['media_type'] == 'text/html'),
                                             sum(1 for r in rs if r['media_type'] != 'text/html'), len({r['vintage_id'] for r in rs})))
    w('| **Total** | **%d** | | | |' % len(props))
    pt = collections.Counter((r['evidence_of_document'].get('page') or {}).get('page_type') for r in props
                             if r['media_type'] == 'text/html')
    w('\nWeb pages by type: %s.\n' % ', '.join('%s %d' % (k, v) for k, v in sorted(pt.items(), key=lambda kv: str(kv[0]))))

    w('## 5. Safe mappings proposed\n')
    w('%d candidates (%d vintages, %d wines) would be eligible for a new mapping. None is applied. Each still needs an '
      'evidence decision recorded for its bytes, which is M3.6B\'s to decide.\n'
      % (len(safe), len({r['vintage_id'] for r in safe}), len({r['wine'] for r in safe})))
    w('| Wine | Vintage | Page | Identity (main heading) | Vintage from | Matches set aside |\n|---|---:|---|---|---|---:|')
    for r in safe:
        pe = r['positive_evidence']
        w('| %s | %d | `%s` | %s | %s | %d |' % (r['wine_name'], r['vintage'], (r['first_url'] or r['artifact'])[8:70],
                                                pe['identity'], pe['vintage_source'], len(pe['excluded_matches_set_aside'])))
    w('\n- **Paloumey 2022:** the page\'s own heading is the wine and year. Its "other vintages" carousel and its range '
      'strip, which names Plume de Paloumey, are set aside. The site\'s 2016 page is not attributed to 2022 (section 7).')
    w('- **Couhins-Lurton blanc 2019 (bottle-image pages):** the heading states the full name, the year and the colour, '
      'and the colour is the model wine\'s.')
    w('- **Château Corbin 2018 (news posts):** the heading is the wine\'s exact name and the year. A news page is not '
      'refused for being news; it is accepted on the evidence of its own heading. The guide\'s publication year in its '
      'text is not read as the vintage.\n')

    w('## 6. The R1 false-positive gate\n')
    w('- **SAFE rows breaking R1:** %d.' % len(gate))
    w('  - No acceptance rests on a tab title, a site name, a sidebar, a related product, a recommendation, an '
      'archive or listing entry, a greeting year, a URL, a filename, a sentence date, or an excluded region.'
      if not gate else '  - **%d SAFE rows break R1.**' % len(gate))
    w('- **Reader acceptances the document\'s evidence rejects:** %s, in %d classes, %d of them not already named.'
      % (_f(len(fp)), len({r['reader_false_positive']['class'] for r in fp}), len(unknown)))
    w('  - No new false-positive class appeared: every one falls in a class M3.5 or R1 already names.'
      if not unknown else '  - **New classes appeared.**')
    w('')
    w('| Reader false-positive class | Candidates |\n|---|---:|')
    for c, n in sorted(collections.Counter((r['reader_false_positive']['class'], r['reader_false_positive']['rule'])
                                           for r in fp).items(), key=lambda kv: (-kv[1], kv[0])):
        w('| %s — %s | %d |' % (c[0], c[1], n))
    veto = [r for r in props if r['evidence_of_document']['disposition'] == 'SAFE_TO_MAP' and r['disposition'] != 'SAFE_TO_MAP'
            and r['disposition'] != 'ALREADY_SUPPORTED']
    w('\n**Reader vetoes.** %d candidates where the document\'s evidence holds but the reader refuses; the stricter '
      'answer stands:\n' % len(veto))
    for r in veto:
        w('- %s %d `%s`: %s' % (r['wine_name'], r['vintage'], (r['first_url'] or r['artifact'])[8:80], r['reader']['why']))
    w('')

    w('## 7. Changes since the blocked run\n')
    old = blocked['by_candidate']
    moved = collections.Counter((old.get(r['candidate']), r['disposition']) for r in props if old.get(r['candidate']) != r['disposition'])
    w('%s candidates changed disposition. All %d of the blocked run\'s SAFE_TO_MAP were re-judged; %d of them stay SAFE.\n'
      % (_f(sum(moved.values())), blocked['dispositions'].get('SAFE_TO_MAP', 0),
         sum(1 for r in props if old.get(r['candidate']) == 'SAFE_TO_MAP' and r['disposition'] == 'SAFE_TO_MAP')))
    w('| Blocked run | This run | Candidates |\n|---|---|---:|')
    for (a, b), n in sorted(moved.items(), key=lambda kv: (-kv[1], kv[0])):
        w('| %s | %s | %d |' % (a, b, n))
    was_safe = collections.Counter(r['disposition'] for r in props if old.get(r['candidate']) == 'SAFE_TO_MAP')
    w('\nWhere the blocked run\'s 144 SAFE_TO_MAP went: %s.' % ', '.join('%s %d' % kv for kv in sorted(was_safe.items())))
    new_safe = [r for r in safe if old.get(r['candidate']) != 'SAFE_TO_MAP']
    w('\nSAFE now, not SAFE then: %d, pages the old flattened-text rules refused (Paloumey\'s for its other-vintages '
      'carousel): %s.\n'
      % (len(new_safe), ', '.join(sorted({'%s %d' % (r['wine_name'], r['vintage']) for r in new_safe})) or 'none'))

    w('## 8. The correction audit\n')
    oc = blocked['correction_by_decision']
    same = sum(1 for c in corr if oc.get(c['decision']) == [c['category'], c['proposed_action']])
    w('- **Re-examined:** %d accepted claims M3.5 found wrong, each on the document\'s own words. The evidence store was '
      'not touched, and every historical decision stands as recorded.' % len(corr))
    w('- **Against the blocked run:** %d of %d decisions get the same category and action; %d are new to this run; %d '
      'blocked-run decisions are missing here.' % (
        same, len(corr), sum(1 for c in corr if c['decision'] not in oc), sum(1 for d in oc if d not in {c['decision'] for c in corr})))
    w('')
    w('| Category | Decisions | Proposed action |\n|---|---:|---|')
    for (cat, act), n in sorted(collections.Counter((c['category'], c['proposed_action']) for c in corr).items()):
        w('| %s | %d | %s |' % (cat, n, act))
    repl = sum(1 for c in corr if c['replacement']['established'])
    w('\n- **Correct replacement already established:** %d decisions. The document\'s own wine and vintage is already '
      'accepted on the same bytes, so the corrected fact exists and only the wrong acceptance needs superseding.' % repl)
    w('- **No correct replacement in the model:** %d decisions. The document is a wine the model does not list: '
      'Château Galland, Château Braude Fellonneau, Cuvée de Mongravey.' % sum(
        1 for c in corr if not c['replacement']['established'] and not (c['actual'] or {}).get('wine')))
    w('- **Cuvée de Mongravey:** its sheets are not forced into Château Mongravey. Where they were accepted as the '
      'château, the proposal is RETAIN_AS_HISTORICAL_ACCEPTANCE_BUT_FLAG: the estate may be right, the wine is not, and '
      'the model holds no wine to supersede with.')
    w('\nExamples of each systematic error:\n')
    seen = set()
    for c in corr:
        for s in c['systematic'] or ['UNLISTED_CUVEE: the estate\'s own cuvée, a wine the model does not list, accepted as the château']:
            k = s.split(':')[0]
            if k in seen:
                continue
            seen.add(k)
            w('- **%s:** decision on `%s`, accepted as %s %s. The document is "%s". %s.' % (
                k, (c['files'] or [''])[-1], c['wine_name'], c['original']['vintage'],
                ' '.join(str(x) for x in c['document_is']['title'] if x), s.split(': ', 1)[-1][:1].upper() + s.split(': ', 1)[-1][1:]))
    w('\n**Proposed correction policy:**')
    w('- The historical acceptance is never edited.')
    w('- A correction is a new decision that supersedes it, citing the document\'s own title.')
    w('- WITHDRAW_ACCEPTANCE is not proposed anywhere: every wrong claim here is contradicted by positive evidence (the '
      'document\'s title), never merely unsupported.\n')

    w('## 9. Extraction opportunities\n')
    ex = collections.Counter(f for r in safe for f in r.get('extraction_opportunity') or [])
    w('Recorded, not extracted: the core figures the model does not hold for each SAFE candidate\'s vintage.\n')
    w('| Figure | SAFE candidates whose vintage lacks it |\n|---|---:|')
    for f in sorted(EXTRACT, key=lambda f: (-ex[f], f)):
        w('| %s | %d |' % (EXTRACT[f], ex[f]))
    w('')

    w('## 10. Open identity and conflict cases\n')
    blk = [r for r in props if r['disposition'] in ('IDENTITY_BLOCKED', 'CONFLICT')]
    w('%d candidates are IDENTITY_BLOCKED or CONFLICT. No candidate resolves Echo, Lions de Batailley, Hauts de '
      'Lynch-Moussas, Haut-Bailly II, Terrasses, D1, D2 or D5. The correction audit leaves every M3.5 conflict where it '
      'was.\n' % len(blk))

    w('## 11. What is what\n')
    w('- **Eligible for a new mapping:** %d candidates (section 5). They are proposals, each needing an evidence '
      'decision.' % len(safe))
    w('- **Merely held:** the other %s candidates. Their documents stay in the store, unlinked, each with the reason '
      'it cannot be mapped.' % _f(len(props) - len(safe)))
    w('- **Historical decisions now believed wrong:** %d accepted claims (section 8). They are recorded as they were.' % len(corr))
    w('- **Corrected facts not yet applied:** %d supersessions and %d flags, all proposals.\n' % (
        sum(1 for c in corr if c['proposed_action'] == 'SUPERSEDE_WITH_CORRECTED_DECISION'),
        sum(1 for c in corr if c['proposed_action'] == 'RETAIN_AS_HISTORICAL_ACCEPTANCE_BUT_FLAG')))

    w('## 12. Recommended M3.6B scope\n')
    w('- **Map the %d SAFE candidates.** For each, first record an evidence decision citing its heading and the '
      'web-page rule fingerprint, then a provenance-linked attribution, as M3.4B and M3.5 did.' % len(safe))
    w('- **Record the corrections as new superseding decisions.** The historical acceptance stays. The evidence store '
      'keeps one decision file per decider version, and the latest decision for a context wins, so a supersession is '
      'a new versioned decision row: no evidence-schema change is needed. Each must cite the document\'s title. The '
      'model\'s Attribution already has `supersedes` and a SUPERSEDED status. The flags (Cuvée de Mongravey) stay '
      'audit records. Which decider version and codes to use is M3.6B\'s to decide.')
    w('- **Leave the merely-held documents** for acquisition planning. Their reasons say which need a better source.\n')
    if gate or unknown:
        w('**Gate: BLOCKED — M3.6A READER REQUIRES ANOTHER CONTROLLED RULE UPDATE**\n')
    else:
        w('**Gate: SAFE — M3.6A FRESH AUDIT COMPLETE — READY FOR M3.6B MAPPING/CORRECTION REVIEW**\n')
    return '\n'.join(out)
