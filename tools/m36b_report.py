"""M3.6B: the report of the application, generated from its manifests, the store and git (never edited by hand)."""
import collections
import json
import subprocess

import data_gap_analysis as A
import evidence_store as ST
import historical_m2_scope as H
import migration_lib as L

BEFORE = '35f8df8'               # M3.6A's fresh audit


def _git(*a):
    return subprocess.check_output(['git'] + list(a), cwd=L.ROOT).decode('utf-8')


def _f(n):
    return '{:,}'.format(n)


def _rows(path):
    try:
        return L.jsonl_lines(path)
    except FileNotFoundError:
        return []


def report(maps, sup, flags):
    import importlib.util
    spec = importlib.util.spec_from_file_location('m36b', L.ROOT + 'tools/m36b-apply.py')
    B = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(B)
    mrows, crows, frows = _rows(B.MAPPINGS), _rows(B.CORRECTIONS), _rows(B.FLAGS)
    v6 = H.m36b_evidence_rows()
    m0 = json.loads(_git('show', '%s:data/model/manifest.json' % BEFORE))
    m1 = json.load(open(L.MODEL + 'manifest.json', encoding='utf-8'))
    changed = sorted(f[len('data/model/'):] for f in _git('diff', '--name-only', BEFORE, '--', 'data/model').split())
    changed, m1 = H.without_m36d(changed, m1)               # M3.6D's wine, a later decision, taken out
    ev_changed = sorted((set(_git('diff', '--name-only', BEFORE, '--', 'data/evidence').split())
                         | set(_git('ls-files', '--others', '--exclude-standard', '--', 'data/evidence').split()))
                        - {'data/evidence/decisions-v%d.jsonl' % v for v in (H.M36E_EVIDENCE_VERSION, H.M36H_EVIDENCE_VERSION)})   # M3.6E's and M3.6H's, later corrections
    reg = L.jsonl_lines(L.ROOT + 'data/audit/data-gap-register.jsonl')
    regd = [g for g in reg if any(b['phase'] == 'M3.6B' for b in (g.get('resolution') or {}).get('by', []))]
    out = []
    w = out.append

    w('# Phase M3.6B — M3.6A\'s audited mappings and evidence corrections, applied\n')
    w('Generated by `python tools/m36b-apply.py --report` from its manifests '
      '(`data/audit/m3.6b-mapping-application.jsonl`, `data/audit/m3.6b-correction-application.jsonl`, '
      '`data/audit/m3.6b-historical-flags.jsonl`), the evidence store and git; never edited by hand.\n')
    w('**M3.6B corrected evidence history without erasing the historical record.**\n')

    w('## 1. Before application\n')
    w('| | At `%s` (M3.6A) |\n|---|---:|' % BEFORE)
    w('| Evidence decisions (v1-v5) | %s |' % _f(H.evidence_rows_before_m36b()))
    w('| Evidence versions | %s |' % ', '.join('v%d' % v for v in H.evidence_versions_before_m36b()))
    w('| Model attributions | %s |' % _f(m0['files']['document/attributions.jsonl']['rows']))
    w('| Model provenance rows | %s |' % _f(m0['files']['cross/provenance.jsonl']['rows']))
    w('| Allow-list: mappings (M3.6A SAFE_TO_MAP) | %d |' % len(maps))
    w('| Allow-list: supersessions (with replacement / without) | %d (%d / %d) |' % (
        len(sup), sum(1 for c in sup if c['replacement']['established']), sum(1 for c in sup if not c['replacement']['established'])))
    w('| Allow-list: historical flags (Cuvée de Mongravey) | %d |' % len(flags))
    w('\nThe allow-lists are read from M3.6A\'s committed outputs and verified, counts and ids, before anything is '
      'written; any difference stops the run (`BLOCKED - ...`). Nothing outside them was mapped, corrected or flagged.\n')

    w('## 2. The representation chosen\n')
    w('The evidence store already versions decisions:')
    w('- one append-only file per decider version;')
    w('- `evidence_store.latest_by_context()` reads, for each question, the answer of the highest version that asked it.\n')
    w('M3.6B uses that, and adds the least it needs:')
    w('- **Decider version 6.** Its reader fingerprint is that of the rules that decide (`tools/m35_rubric.py` + '
      '`tools/web_evidence.py`): `%s`. The store\'s rule holds: a version is one reader.' % B.decider_fingerprint())
    w('- **A mapping** is a v6 ACCEPTED row (kind `web_page_review`) for the page\'s estate, wine and vintage. It reads '
      'the held bytes under `sources/discovery/` (path and SHA-256), and its evidence is the page\'s main heading and '
      'vintage source.')
    w('- **A correction** is a v6 REFUSED row asking exactly the question the historical v5 row asked: the same artifact '
      'and context, so its row key differs only in `v`. `latest_by_context()` now reads the correction; the v5 row is '
      'untouched. The relation is explicit:')
    w('  - `supersedes` names the v5 row (row key, version, decision, code);')
    w('  - `code` is the precise M3.6A category (WRONG_ESTATE, WRONG_WINE), not a broad CORRECTED state;')
    w('  - `replacement` names the accepted decision for the document\'s own target, and its model attribution where one exists;')
    w('  - `document_is` keeps what the document is, even when the model has no such wine.')
    w('- **A historical flag** is an audit record (`data/audit/m3.6b-historical-flags.jsonl`), not a decision. The '
      'v5 acceptance stays the latest answer. The model\'s findings could hold it, but a new finding changes the gap '
      'register\'s identity counts, which M3.6B may not touch.')
    w('- **Git provenance.** Every v6 row carries the git state it was written in (the store requires it from v4 on).')
    w('  - The runs were made with the M3.6B code not yet committed and the three retained blocked-run files present, '
      'so the rows say `dirty`. Their `status_hash` names that exact state: the store\'s provenance mechanism, not a gap.')
    w('  - `--check` recomputes every row and compares all of it but that stamp, which must name a commit in HEAD\'s history.\n')

    w('## 3. The eight mappings\n')
    w('| Wine | Vintage | Page | Main heading | Vintage from | Colour | Attribution | v6 decision |\n'
      '|---|---:|---|---|---|---|---|---|')
    for r in mrows:
        w('| %s | %d | `%s` | %s | %s | %s | `%s` | ACCEPTED |' % (
            r['wine_name'], r['vintage'], (r['first_url'] or '')[8:70], r['identity'], r['vintage_source'],
            (r['colour'] or '').lower() or '—', r['attribution']))
    w('\n- **Paloumey 2022:** French and English pages. Their "other vintages" carousels and range strips are set '
      'aside as excluded regions, so no 2013, 2016, 2018 or 2019 attribution was made.')
    w('- **Couhins-Lurton blanc 2019:** three bottle-image pages, mapped to the model\'s white wine only. The red is untouched.')
    w('- **Château Corbin 2018:** three pages whose own heading is the wine and year. The guide\'s 2022 is not the '
      'vintage, and the three press-dossier PDFs the reader refused are not mapped.')
    w('- **Model changes:** each mapping is an Attribution (DOCUMENT_TEXT, ACCEPTED, role FIRST) through the migration\'s '
      'M6 step `m36b_mappings`. Its DOCUMENT provenance names its v6 decision, its heading and its vintage source. A '
      'fetched page had no manifest attribution, so there is none to preserve or derive from.\n')

    w('## 4. The %d corrections\n' % len(crows))
    if crows:
        c = collections.Counter((r['category'], bool(r['replacement']['decision'])) for r in crows)
        w('| Category | With replacement | Without | Total |\n|---|---:|---:|---:|')
        for cat in sorted({k[0] for k in c}):
            w('| %s | %d | %d | %d |' % (cat, c[(cat, True)], c[(cat, False)], c[(cat, True)] + c[(cat, False)]))
        w('')
        w('- **With replacement (%d).** The document\'s own wine and vintage is already accepted on the same bytes. The '
          'correction links to that decision and, where M3.5 attributed it, to the model attribution (%d). No evidence '
          'is duplicated.' % (sum(1 for r in crows if r['replacement']['decision']),
                              sum(1 for r in crows if r['replacement']['attribution'])))
        unl = collections.Counter((r['document_is']['title'][0] or '?') for r in crows if not r['replacement']['decision'])
        w('- **Without replacement (%d).** The document is a wine the model does not list (%s). The correction refuses '
          'the wrong attribution and keeps what the document is; no wine is created.' % (
              sum(unl.values()), ', '.join('"%s" %d' % kv for kv in sorted(unl.items()))))
        by_title = collections.Counter((r['document_is']['title'][0] or '?') for r in crows)
        w('- **Documents:** %s.\n' % ', '.join('%s %d' % kv for kv in sorted(by_title.items())))
    else:
        w('Not yet applied (stage 2).\n')

    w('## 5. The %d historical flags\n' % len(frows))
    if frows:
        w('Each Cuvée de Mongravey sheet accepted as Château Mongravey keeps its acceptance, flagged:\n')
        w('> %s\n' % B.FLAG_REASON)
        w('No Cuvée de Mongravey wine was created, Château Mongravey was not renamed, and no replacement was invented.\n')
    else:
        w('Not yet recorded (stage 2).\n')

    w('## 6. Historical immutability\n')
    w('- **Files:** `data/evidence/decisions-v1.jsonl` … `decisions-v5.jsonl` are byte-identical to `%s`, and so are '
      'their index entries. The store verifies against its index.' % BEFORE)
    w('- **Evidence diff since `%s`:** %s.' % (BEFORE, ', '.join('`%s`' % f for f in ev_changed) or 'none'))
    w('- **v6 holds %d rows:** %d ACCEPTED mappings and %d REFUSED corrections, exactly the rows the manifests name.' % (
        len(v6), sum(1 for d in v6 if d['kind'] == 'web_page_review'), sum(1 for d in v6 if d['kind'] == 'correction')))
    w('- **The 219 decisions:** each historical decision a correction or flag names is still ACCEPTED in v5, with its '
      'artifact, hash and context.\n')

    w('## 7. Model, canonical data and app\n')
    w('| Model file changed since `%s` | Rows before | Rows after |\n|---|---:|---:|' % BEFORE)
    for f in changed:
        if f in m0.get('files', {}):
            w('| `%s` | %s | %s |' % (f, _f(m0['files'][f]['rows']), _f(m1['files'][f]['rows'])))
        else:
            w('| `%s` | | |' % f)
    w('')
    w('- **Model:** only attributions, provenance, the vintage-documents index and the manifest changed, all additions.')
    w('- **Unchanged:** canonical values, observations, reconciliations, findings, identities and state.')
    w('- **App:** `data/app/` and the legacy data files are unchanged; the app data still projects from the model byte '
      'for byte. No presentation change.\n')

    w('## 8. Gap register\n')
    if regd:
        w('M3.6B is recorded, with its commit, on %d estate gap(s) (`VINTAGE_NO_DOCUMENT`): %s.' % (
            len(regd), ', '.join('%s %d → %d' % (g['entity_id'], g['resolution']['affected_before'],
                                                 g['resolution']['affected_after']) for g in regd)))
        w('Only "no document" is resolved; the vintages\' figures stay with their own gaps, and no other gap changed.\n')
    else:
        w('Not yet recorded: it follows the mapping commit, as for M3.4B and M3.5.\n')

    w('## 9. Tests and reproducibility\n')
    w('- **`tools/test-m36b.py`** checks:')
    w('  - the exact allow-list mappings, their identities and the absence of extra mappings;')
    w('  - the Paloumey carousel, the Couhins-Lurton colour and the Corbin guide date;')
    w('  - every mapping\'s v6 decision and provenance;')
    w('  - the 199 superseding decisions, each asking its v5 question, with the 62 replacements and no invented wine;')
    w('  - the 20 flags;')
    w('  - historical immutability, the safety invariants, and that everything recomputes.')
    w('- **Earlier suites** admit M3.6B through `tools/historical_m2_scope.py`, which names each change exactly:')
    w('  - its model rows;')
    w('  - its v6 evidence beside v1-v5 (`evidence_changes_are_m36b_only`, `evidence_rows_before_m36b`);')
    w('  - the Phase 4 protected "evidence" group (`protected_group`: v1-v5 byte for byte, the index without the v6 entry).')
    w('  - Every assertion about v1-v5 and every other group stands.')
    w('- **Reproducibility:** each stage was run twice from the identical pre-stage state, restored between runs; '
      'the model, index, evidence and manifest outputs were byte-identical.\n')

    w('## 10. Remaining open decisions\n')
    w('None was resolved: D1, D2, D5, La Parde / Haut-Bailly II, Terrasses, Batailley / Lions de Batailley, the '
      'Lynch-Moussas second wine, Pichon Baron\'s second wine. The 179 D1 findings and 7 conflicts stay open. The 20 '
      'flagged Cuvée de Mongravey acceptances await a decision on whether the model should hold that wine.\n')
    complete = len(mrows) == 8 and len(crows) == 199 and len(frows) == 20 and regd
    w('**Gate: %s**\n' % ('SAFE — M3.6B AUDITED MAPPINGS AND EVIDENCE CORRECTIONS APPLIED' if complete else
                          'IN PROGRESS — stage %s of M3.6B applied' % ('1' if not crows else '2')))
    return '\n'.join(out)
